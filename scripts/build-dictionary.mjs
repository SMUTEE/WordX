// Builds the word data the game ships with:
//   src/data/dictionary.generated.ts — every 4-, 5- and 6-letter A–Z word, to validate guesses
//   src/data/pools.generated.ts      — answer pools for Journey levels, banded by how common words are
// Commonness comes from SCOWL's frequency tiers (wordlist-english): tier 10 is the most common.
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const all = require('an-array-of-english-words')
const scowl = require('wordlist-english')

const LENGTHS = [4, 5, 6]
const az = (w) => /^[a-z]+$/.test(w)

// ---------- Guess dictionary ----------
const guessWords = [...new Set(all.filter((w) => az(w) && LENGTHS.includes(w.length)).map((w) => w.toUpperCase()))].sort()

// ---------- Answer pools ----------
// Never an answer: offensive, sexual, or upsetting words. (They can still be typed as guesses.)
const BLOCK = new Set(
  `arse arses bitch boner boobs booby busty butts cocks coons crack crap craps cunts damn dicks dildo dyke dykes fanny farts fucks gonad gooks gypsy hoes homo horny hussy jizz kike kikes knobs lesbo lezzy nazis negro nudes paedo pecker penis penal perve pervs pimps piss porno porn prick pubes pubic pussy queer rape raped raper rapes rapist retard sados scrot screw semen sexed sexes sexy shags shits sissy skank slags sluts smut spunk tits titty toke turds twats vagina vulva whore wanks wench willy dead death dying kill killer kills murder suicide slave slaves bomb bombs rifle drunk drugs nigga nigger chink spick spics wetback tranny trannys hooker`
    .split(/\s+/)
    .filter(Boolean),
)

const tier = (n) => new Set((scowl[`english/${n}`] ?? []).filter(az))
const T10 = tier(10)
const T20 = tier(20)
const T35 = tier(35)
const common = new Set([...T10, ...T20, ...T35])

/** Drops inflections (plurals, -ed, -ing, comparatives) whose base form is also a word. */
function isBaseForm(w) {
  const has = (x) => common.has(x)
  if (w.endsWith('s') && !/(ss|us|is|ous)$/.test(w) && (has(w.slice(0, -1)) || has(w.slice(0, -2)))) return false
  if (w.endsWith('ed') && (has(w.slice(0, -1)) || has(w.slice(0, -2)) || has(w.slice(0, -3)))) return false
  if (w.endsWith('ing') && (has(w.slice(0, -3)) || has(`${w.slice(0, -3)}e`))) return false
  if (/(er|est)$/.test(w) && (has(w.slice(0, -2)) || has(w.slice(0, -3)) || has(w.slice(0, -1)))) return false
  return true
}

const pool = (sets, length, extra = () => true) =>
  [...new Set(sets.flatMap((s) => [...s]))]
    .filter((w) => w.length === length && isBaseForm(w) && !BLOCK.has(w) && extra(w))
    .map((w) => w.toUpperCase())
    .sort()

const VOWELS = /[aeiou]/g
const vowelCount = (w) => (w.match(VOWELS) ?? []).length

// Trap words: many look-alikes one letter apart (_IGHT, _OUND), where Classic gets hard.
const fiveCommon = [...common].filter((w) => w.length === 5)
const patterns = new Map()
for (const w of fiveCommon) for (let i = 0; i < 5; i++) {
  const p = `${w.slice(0, i)}_${w.slice(i + 1)}`
  patterns.set(p, (patterns.get(p) ?? 0) + 1)
}
const neighbours = (w) => Math.max(...[0, 1, 2, 3, 4].map((i) => patterns.get(`${w.slice(0, i)}_${w.slice(i + 1)}`) ?? 0)) - 1

// Unique anagrams across the whole dictionary, so one arrangement is the only real word.
const signature = (w) => [...w].sort().join('')
const sigCount = new Map()
for (const w of guessWords) sigCount.set(signature(w.toLowerCase()), (sigCount.get(signature(w.toLowerCase())) ?? 0) + 1)

const POOLS = {
  four_easy: pool([T10, T20], 4),
  five_easy: pool([T10], 5),
  five_common: pool([T20], 5),
  five_medium: pool([T20, T35], 5),
  five_vowel: pool([T10, T20], 5, (w) => !w.includes('y') && vowelCount(w) >= 1 && vowelCount(w) <= 2),
  five_anagram: pool([T20, T35], 5, (w) => sigCount.get(signature(w)) === 1 && new Set(w).size >= 4),
  five_trap: pool([T10, T20, T35], 5, (w) => neighbours(w) >= 4),
  five_hard: pool([T35], 5, (w) => /[jqxzvkw]/.test(w) || new Set(w).size < 5 || vowelCount(w) === 1),
  four_medium: pool([T35], 4),
  six_common: pool([T10, T20], 6),
  six_medium: pool([T35], 6),
}

writeFileSync(
  new URL('../src/data/dictionary.generated.ts', import.meta.url),
  `// Generated by scripts/build-dictionary.mjs — do not edit by hand.\nexport const DICTIONARY_WORDS = ${JSON.stringify(guessWords.join(' '))}\n`,
)
writeFileSync(
  new URL('../src/data/pools.generated.ts', import.meta.url),
  `// Generated by scripts/build-dictionary.mjs — do not edit by hand.\n// Journey answer pools, banded by SCOWL frequency tier.\nexport const POOLS = {\n${Object.entries(POOLS)
    .map(([k, v]) => `  ${k}: ${JSON.stringify(v.join(' '))},`)
    .join('\n')}\n} as const\n\nexport type PoolName = keyof typeof POOLS\n`,
)
console.log(`dictionary: ${guessWords.length} words`)
for (const [k, v] of Object.entries(POOLS)) console.log(`${k.padEnd(14)} ${String(v.length).padStart(5)}  ${v.slice(0, 8).join(' ')}`)
